-- More snapshot lanes, optional engine metrics URL, and per-key start samples (#508 #510).
ALTER TABLE triage_snapshot DROP CONSTRAINT triage_snapshot_lane_valid;
ALTER TABLE triage_snapshot ADD CONSTRAINT triage_snapshot_lane_valid CHECK (lane IN (
    'ACTIVE', 'SUSPENDED', 'COMPLETED', 'FAILED', 'RETRYING', 'OUT_OF_SCOPE_DLQ',
    'HISTORY_BACKLOG', 'PROC_STARTED', 'PROC_FINISHED',
    'TASK_CREATED', 'TASK_COMPLETED', 'CASE_STARTED'));

ALTER TABLE engine_registry ADD COLUMN metrics_url text;

CREATE TABLE triage_start_by_key (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engine_id text NOT NULL,
    definition_key text NOT NULL,
    count bigint NOT NULL,
    catalog_capped boolean NOT NULL,
    sampled_at timestamptz NOT NULL
);
CREATE INDEX idx_triage_start_by_key_engine_ts ON triage_start_by_key (engine_id, sampled_at DESC);
